USE DATABASE RISK_DEV_DB;

-- 1. SCHEMAS
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS ENG;

-- 2. RAW TRANSIENT STAGING TABLES FOR FACT INGESTION
CREATE TRANSIENT TABLE IF NOT EXISTS RAW.STG_DAILY_POSITIONS_DELTA (
    POSITION_DATE DATE,
    PORTFOLIO_ID VARCHAR(50),
    COUNTERPARTY_ID VARCHAR(50),
    INSTRUMENT_ID VARCHAR(50),
    SETTLED_QUANTITY NUMBER(38,4),
    BOOK_VALUE NUMBER(38,2),
    MARKET_VALUE NUMBER(38,2),
    UNREALIZED_PNL NUMBER(38,2)
);

CREATE TRANSIENT TABLE IF NOT EXISTS RAW.STG_SETTLED_TRANSACTIONS_DELTA (
    TRANSACTION_ID VARCHAR(50),
    TRANSACTION_DATE DATE,
    SETTLEMENT_DATE DATE,
    PORTFOLIO_ID VARCHAR(50),
    COUNTERPARTY_ID VARCHAR(50),
    INSTRUMENT_ID VARCHAR(50),
    TRANSACTION_TYPE VARCHAR(50),
    QUANTITY NUMBER(38,4),
    PRICE NUMBER(38,4),
    SETTLED_AMOUNT NUMBER(38,2),
    CURRENCY VARCHAR(10)
);

-- 3. ENG PRODUCTION FACT TABLES
CREATE TABLE IF NOT EXISTS ENG.FACT_DAILY_POSITIONS_ABOR (
    POSITION_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    POSITION_DATE DATE NOT NULL,
    PORTFOLIO_ID VARCHAR(50) NOT NULL,
    COUNTERPARTY_ID VARCHAR(50) NOT NULL,
    INSTRUMENT_ID VARCHAR(50) NOT NULL,
    SETTLED_QUANTITY NUMBER(38,4) NOT NULL,
    BOOK_VALUE NUMBER(38,2) NOT NULL,
    MARKET_VALUE NUMBER(38,2) NOT NULL,
    UNREALIZED_PNL NUMBER(38,2) NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ENG.FACT_SETTLED_TRANSACTIONS (
    TRANSACTION_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    TRANSACTION_ID VARCHAR(50) NOT NULL,
    TRANSACTION_DATE DATE NOT NULL,
    SETTLEMENT_DATE DATE NOT NULL,
    PORTFOLIO_ID VARCHAR(50) NOT NULL,
    COUNTERPARTY_ID VARCHAR(50) NOT NULL,
    INSTRUMENT_ID VARCHAR(50) NOT NULL,
    TRANSACTION_TYPE VARCHAR(50) NOT NULL,
    QUANTITY NUMBER(38,4) NOT NULL,
    PRICE NUMBER(38,4) NOT NULL,
    SETTLED_AMOUNT NUMBER(38,2) NOT NULL,
    CURRENCY VARCHAR(10) NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
