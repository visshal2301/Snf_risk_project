-- V1.0.0__initial_schema.sql
-- Description: Core Schema Initialization for Multi-Layered Market Risk Analytics Architecture

-- 1. Create Core Internal Stages for UDFs & Stored Procedures
CREATE STAGE IF NOT EXISTS SYSTEM_UDF_STAGE
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Stage for storing UDF dependencies and python artifacts';

CREATE STAGE IF NOT EXISTS SYSTEM_SPROC_STAGE
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Stage for storing Stored Procedure binaries and scripts';

-- 2. Create RAW and ANALYTICS Schemas
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

-- 3. RAW Ingestion Layer Tables
CREATE TABLE IF NOT EXISTS RAW.RAW_POSITIONS (
    AS_OF_DATE DATE,
    PORTFOLIO VARCHAR(100),
    INSTRUMENT_ID VARCHAR(100),
    RISK_FACTOR VARCHAR(100),
    SIGNED_MARKET_VALUE NUMBER(38, 2),
    CURRENCY VARCHAR(10),
    SOURCE_FILE VARCHAR(255),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW.RAW_FACTOR_RETURNS (
    SCENARIO_DATE DATE,
    RISK_FACTOR VARCHAR(100),
    FACTOR_RETURN FLOAT,
    SOURCE_FILE VARCHAR(255),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 4. ANALYTICS Layer Tables
CREATE TABLE IF NOT EXISTS ANALYTICS.RISK_SCENARIO_PNL (
    RUN_ID VARCHAR(100),
    AS_OF_DATE DATE,
    PORTFOLIO VARCHAR(100),
    SCENARIO_DATE DATE,
    PNL_USD NUMBER(38, 2),
    LOSS_USD NUMBER(38, 2),
    CALCULATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ANALYTICS.RISK_METRICS (
    RUN_ID VARCHAR(100),
    AS_OF_DATE DATE,
    PORTFOLIO VARCHAR(100),
    CONFIDENCE FLOAT,
    HORIZON_DAYS NUMBER(10, 0),
    SCENARIO_COUNT NUMBER(10, 0),
    VAR_USD NUMBER(38, 2),
    ES_USD NUMBER(38, 2),
    CALCULATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
