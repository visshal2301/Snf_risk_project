USE DATABASE RISK_DEV_DB;
USE SCHEMA ENG;

CREATE TABLE IF NOT EXISTS ENG.AUDIT_EXECUTION_LOG (
    LOG_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    PIPELINE_NAME VARCHAR(100) NOT NULL,
    SUBJECT_AREA VARCHAR(50) NOT NULL,
    TARGET_PARTITION VARCHAR(50) NOT NULL,
    STATUS VARCHAR(20) NOT NULL, -- 'STARTED', 'SUCCESS', 'FAILED'
    STAGED_ROW_COUNT NUMBER(38,0) DEFAULT 0,
    LOADED_ROW_COUNT NUMBER(38,0) DEFAULT 0,
    DELETED_ROW_COUNT NUMBER(38,0) DEFAULT 0,
    EXPIRED_ROW_COUNT NUMBER(38,0) DEFAULT 0,
    WARNING_COUNT NUMBER(38,0) DEFAULT 0,
    ERROR_MESSAGE VARCHAR(1000),
    EXECUTION_DURATION_SEC NUMBER(10,2) DEFAULT 0.0,
    EXECUTED_BY VARCHAR(100) DEFAULT CURRENT_USER(),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
