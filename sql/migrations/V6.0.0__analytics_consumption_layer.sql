USE SCHEMA ANALYTICS;

-- 1. Executive Portfolio Risk & Return View
CREATE OR REPLACE VIEW ANALYTICS.VW_EXECUTIVE_PORTFOLIO_RISK AS
WITH POS_SUMMARY AS (
    SELECT 
        POSITION_DATE,
        PORTFOLIO_ID,
        SUM(BOOK_VALUE) AS TOTAL_BOOK_VALUE,
        SUM(UNREALIZED_PNL) AS TOTAL_UNREALIZED_PNL,
        COUNT(DISTINCT INSTRUMENT_ID) AS ACTIVE_HOLDINGS_COUNT
    FROM ENG.FACT_DAILY_POSITIONS_ABOR
    GROUP BY POSITION_DATE, PORTFOLIO_ID
),
RISK_SUMMARY AS (
    SELECT 
        METRIC_DATE,
        PORTFOLIO_ID,
        SUM(MARK_TO_MARKET) AS TOTAL_MARKET_VALUE,
        SUM(VALUE_AT_RISK_99) AS TOTAL_VAR_99,
        SUM(POTENTIAL_FUTURE_EXPOSURE) AS TOTAL_PFE_95,
        SUM(CREDIT_VALUE_ADJUSTMENT) AS TOTAL_CVA
    FROM ENG.FACT_DAILY_RISK_METRICS
    GROUP BY METRIC_DATE, PORTFOLIO_ID
)
SELECT 
    r.METRIC_DATE AS SNAPSHOT_DATE,
    p.PORTFOLIO_ID,
    p.PORTFOLIO_NAME,
    p.PORTFOLIO_MANAGER,
    p.INVESTMENT_STRATEGY,
    p.BASE_CURRENCY,
    pos.ACTIVE_HOLDINGS_COUNT,
    ROUND(r.TOTAL_MARKET_VALUE, 2) AS TOTAL_AUM_USD,
    ROUND(pos.TOTAL_BOOK_VALUE, 2) AS TOTAL_BOOK_VALUE_USD,
    ROUND(pos.TOTAL_UNREALIZED_PNL, 2) AS TOTAL_UNREALIZED_PNL_USD,
    ROUND(r.TOTAL_VAR_99, 2) AS TOTAL_VAR_99_USD,
    ROUND(r.TOTAL_PFE_95, 2) AS TOTAL_PFE_95_USD,
    ROUND(r.TOTAL_CVA, 2) AS TOTAL_CVA_USD,
    -- Financial Leverage & Risk Ratios
    ROUND((r.TOTAL_VAR_99 / NULLIF(ABS(r.TOTAL_MARKET_VALUE), 0)) * 100, 2) AS VAR_TO_AUM_PCT,
    ROUND((pos.TOTAL_UNREALIZED_PNL / NULLIF(ABS(pos.TOTAL_BOOK_VALUE), 0)) * 100, 2) AS UNREALIZED_RETURN_PCT
FROM RISK_SUMMARY r
JOIN ENG.DIM_PORTFOLIO p 
  ON r.PORTFOLIO_ID = p.PORTFOLIO_ID AND p.IS_ACTIVE = TRUE
LEFT JOIN POS_SUMMARY pos 
  ON r.METRIC_DATE = pos.POSITION_DATE AND r.PORTFOLIO_ID = pos.PORTFOLIO_ID;


-- 2. Counterparty Credit Concentration & Basel Large Exposure View
CREATE OR REPLACE VIEW ANALYTICS.VW_COUNTERPARTY_CONCENTRATION AS
WITH CPTY_RISK AS (
    SELECT 
        METRIC_DATE,
        COUNTERPARTY_ID,
        SUM(MARK_TO_MARKET) AS EXPOSURE_MTM,
        SUM(VALUE_AT_RISK_99) AS COUNTERPARTY_VAR_99,
        SUM(POTENTIAL_FUTURE_EXPOSURE) AS COUNTERPARTY_PFE_95,
        SUM(CREDIT_VALUE_ADJUSTMENT) AS COUNTERPARTY_CVA,
        COUNT(DISTINCT PORTFOLIO_ID) AS PORTFOLIO_EXPOSURE_COUNT,
        COUNT(DISTINCT INSTRUMENT_ID) AS INSTRUMENT_COUNT
    FROM ENG.FACT_DAILY_RISK_METRICS
    GROUP BY METRIC_DATE, COUNTERPARTY_ID
),
TOTAL_FIRM_RISK AS (
    SELECT 
        METRIC_DATE,
        SUM(MARK_TO_MARKET) AS FIRM_TOTAL_AUM
    FROM ENG.FACT_DAILY_RISK_METRICS
    GROUP BY METRIC_DATE
)
SELECT 
    cr.METRIC_DATE AS SNAPSHOT_DATE,
    c.COUNTERPARTY_ID,
    c.COUNTERPARTY_NAME,
    c.LEI_CODE,
    c.SECTOR,
    c.CREDIT_RATING,
    CASE 
        WHEN c.CREDIT_RATING IN ('AAA', 'AA', 'A', 'BBB') THEN 'Investment Grade'
        ELSE 'High Yield / Speculative'
    END AS RATING_CATEGORY,
    c.JURISDICTION,
    c.NETTING_AGREEMENT_TYPE,
    cr.PORTFOLIO_EXPOSURE_COUNT,
    cr.INSTRUMENT_COUNT,
    ROUND(cr.EXPOSURE_MTM, 2) AS NET_EXPOSURE_USD,
    ROUND(cr.COUNTERPARTY_VAR_99, 2) AS VAR_99_USD,
    ROUND(cr.COUNTERPARTY_PFE_95, 2) AS PFE_95_USD,
    ROUND(cr.COUNTERPARTY_CVA, 2) AS CVA_PROVISION_USD,
    -- Basel Large Exposure concentration percentage
    ROUND((cr.EXPOSURE_MTM / NULLIF(tf.FIRM_TOTAL_AUM, 0)) * 100, 2) AS FIRM_CONCENTRATION_PCT,
    -- Regulatory monitoring flag (Basel Large Exposure standard: > 10% is a large exposure warning)
    CASE 
        WHEN (cr.EXPOSURE_MTM / NULLIF(tf.FIRM_TOTAL_AUM, 0)) * 100 >= 10.0 THEN 'BREACH_WARNING'
        WHEN (cr.EXPOSURE_MTM / NULLIF(tf.FIRM_TOTAL_AUM, 0)) * 100 >= 5.0 THEN 'ELEVATED'
        ELSE 'NORMAL'
    END AS BASEL_CONCENTRATION_STATUS
FROM CPTY_RISK cr
JOIN TOTAL_FIRM_RISK tf ON cr.METRIC_DATE = tf.METRIC_DATE
JOIN ENG.DIM_COUNTERPARTY c 
  ON cr.COUNTERPARTY_ID = c.COUNTERPARTY_ID AND c.IS_ACTIVE = TRUE;


-- 3. Asset Class & Currency Risk Distribution View
CREATE OR REPLACE VIEW ANALYTICS.VW_ASSET_CLASS_RISK_DISTRIBUTION AS
SELECT 
    r.METRIC_DATE AS SNAPSHOT_DATE,
    i.ASSET_CLASS,
    i.SUB_ASSET_CLASS,
    i.CURRENCY,
    COUNT(DISTINCT r.PORTFOLIO_ID) AS PORTFOLIO_COUNT,
    COUNT(DISTINCT r.INSTRUMENT_ID) AS INSTRUMENTS_HELD_COUNT,
    ROUND(SUM(r.MARK_TO_MARKET), 2) AS TOTAL_MARKET_VALUE_USD,
    ROUND(SUM(r.VALUE_AT_RISK_99), 2) AS TOTAL_VAR_99_USD,
    ROUND(SUM(r.POTENTIAL_FUTURE_EXPOSURE), 2) AS TOTAL_PFE_95_USD,
    ROUND(SUM(r.CREDIT_VALUE_ADJUSTMENT), 2) AS TOTAL_CVA_USD,
    ROUND(AVG(r.VALUE_AT_RISK_99), 2) AS AVG_POSITION_VAR_USD
FROM ENG.FACT_DAILY_RISK_METRICS r
JOIN ENG.DIM_INSTRUMENT i 
  ON r.INSTRUMENT_ID = i.INSTRUMENT_ID AND i.IS_ACTIVE = TRUE
GROUP BY r.METRIC_DATE, i.ASSET_CLASS, i.SUB_ASSET_CLASS, i.CURRENCY;


-- 4. Trade Execution & Liquidity Turnover View
CREATE OR REPLACE VIEW ANALYTICS.VW_TRADE_TURNOVER_ANALYTICS AS
SELECT 
    t.TRANSACTION_DATE,
    t.SETTLEMENT_DATE,
    p.PORTFOLIO_NAME,
    p.PORTFOLIO_MANAGER,
    c.COUNTERPARTY_NAME AS BROKER_NAME,
    c.CREDIT_RATING AS BROKER_RATING,
    i.ASSET_CLASS,
    t.TRANSACTION_TYPE,
    t.CURRENCY,
    COUNT(t.TRANSACTION_ID) AS TOTAL_TRADES_COUNT,
    SUM(t.QUANTITY) AS TOTAL_UNITS_TRADED,
    ROUND(SUM(t.SETTLED_AMOUNT), 2) AS TOTAL_VOLUME_USD,
    ROUND(AVG(t.PRICE), 4) AS AVG_EXECUTION_PRICE
FROM ENG.FACT_SETTLED_TRANSACTIONS t
JOIN ENG.DIM_PORTFOLIO p ON t.PORTFOLIO_ID = p.PORTFOLIO_ID AND p.IS_ACTIVE = TRUE
JOIN ENG.DIM_COUNTERPARTY c ON t.COUNTERPARTY_ID = c.COUNTERPARTY_ID AND c.IS_ACTIVE = TRUE
JOIN ENG.DIM_INSTRUMENT i ON t.INSTRUMENT_ID = i.INSTRUMENT_ID AND i.IS_ACTIVE = TRUE
GROUP BY 
    t.TRANSACTION_DATE,
    t.SETTLEMENT_DATE,
    p.PORTFOLIO_NAME,
    p.PORTFOLIO_MANAGER,
    c.COUNTERPARTY_NAME,
    c.CREDIT_RATING,
    i.ASSET_CLASS,
    t.TRANSACTION_TYPE,
    t.CURRENCY;


-- 5. SCD Type 2 Counterparty Credit Migration Audit View
CREATE OR REPLACE VIEW ANALYTICS.VW_COUNTERPARTY_RATING_MIGRATION AS
SELECT 
    COUNTERPARTY_ID,
    COUNTERPARTY_NAME,
    SECTOR,
    JURISDICTION,
    CREDIT_RATING,
    EFFECTIVE_START_DATE,
    EFFECTIVE_END_DATE,
    IS_ACTIVE,
    LAG(CREDIT_RATING) OVER (
        PARTITION BY COUNTERPARTY_ID 
        ORDER BY EFFECTIVE_START_DATE ASC
    ) AS PREVIOUS_RATING,
    CASE 
        WHEN LAG(CREDIT_RATING) OVER (PARTITION BY COUNTERPARTY_ID ORDER BY EFFECTIVE_START_DATE ASC) IS NULL THEN 'INITIAL_RATING'
        WHEN LAG(CREDIT_RATING) OVER (PARTITION BY COUNTERPARTY_ID ORDER BY EFFECTIVE_START_DATE ASC) = CREDIT_RATING THEN 'NO_CHANGE'
        ELSE 'RATING_MIGRATION'
    END AS MIGRATION_EVENT,
    UPDATED_AT AS RECORDED_AT
FROM ENG.DIM_COUNTERPARTY;
